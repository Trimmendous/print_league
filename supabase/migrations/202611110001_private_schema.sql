-- Foundation only. No anonymous access or public mutation RPC is enabled.
-- Apply to a fresh staging project; existing SQLite data is never read or changed.
begin;
create schema if not exists league_private;
revoke all on schema league_private from public, anon, authenticated;
alter default privileges in schema league_private revoke all on tables from public, anon, authenticated;
alter default privileges in schema league_private revoke all on sequences from public, anon, authenticated;
alter default privileges in schema league_private revoke execute on functions from public, anon, authenticated;

create table league_private.members (
 id bigint generated by default as identity primary key,
 display_name text not null check (char_length(display_name) between 1 and 80),
 admin boolean not null default false,
 avatar_key text,
 created_at timestamptz not null default now()
);
-- Normalized keys must be NFKC + Unicode casefold, NOT SQL lower().
-- No API writes are enabled until normalization is shared with the legacy test cases.
create table league_private.identifiers (
 id bigint generated always as identity primary key,
 member_id bigint not null references league_private.members(id) on delete cascade,
 kind text not null check (kind in ('username','email')),
 value text not null,
 normalized text not null check (normalized <> ''),
 verified_at timestamptz,
 unique (kind, normalized), unique (member_id, kind)
);
create table league_private.passwords (
 member_id bigint primary key references league_private.members(id) on delete cascade,
 hash text not null, algorithm text not null, updated_at timestamptz not null default now()
);
create table league_private.identities (
 member_id bigint not null references league_private.members(id) on delete cascade,
 provider text not null check(provider = 'google'), subject text not null,
 primary key(provider, subject), unique(member_id, provider)
);
create table league_private.sessions (
 token_hash text primary key check (length(token_hash)=64),
 member_id bigint not null references league_private.members(id) on delete cascade,
 csrf_hash text not null check(length(csrf_hash)=64),
 created_at timestamptz not null default now(), expires_at timestamptz not null,
 authenticated_at timestamptz not null default now(), revoked_at timestamptz,
 check(expires_at > created_at)
);
create index sessions_member_idx on league_private.sessions(member_id);
create index sessions_expiry_idx on league_private.sessions(expires_at);
create table league_private.invites (
 token_hash text primary key check(length(token_hash)=64),
 created_by bigint references league_private.members(id),
 created_at timestamptz not null default now(), expires_at timestamptz not null,
 redeemed_by bigint references league_private.members(id), redeemed_at timestamptz,
 check((redeemed_at is null) = (redeemed_by is null)), check(expires_at > created_at)
);
create table league_private.recovery_codes (
 member_id bigint not null references league_private.members(id) on delete cascade,
 token_hash text primary key check(length(token_hash)=64), used_at timestamptz
);
create table league_private.rounds (
 id bigint generated by default as identity primary key,
 title text not null check(char_length(title) between 1 and 160),
 phase text not null check(phase in ('submissions','topics','tie','no_topics','printing','judging','completed')),
 topic text not null default '', deadline timestamptz not null,
 creator_id bigint references league_private.members(id), has_prevote boolean not null default false,
 vote_opens_at timestamptz, votes_close_at timestamptz, printing_started_at timestamptz,
 created_at timestamptz not null default now(),
 check(vote_opens_at is null or vote_opens_at < deadline),
 check(votes_close_at is null or votes_close_at <= deadline),
 check(vote_opens_at is null or votes_close_at is null or vote_opens_at < votes_close_at)
);
create table league_private.topics (
 id bigint generated by default as identity primary key,
 round_id bigint not null references league_private.rounds(id) on delete cascade,
 user_id bigint not null references league_private.members(id),
 title text not null check(char_length(title) between 1 and 160), normalized text not null,
 unique(round_id,normalized), unique(round_id,id)
);
create table league_private.votes (
 round_id bigint not null references league_private.rounds(id) on delete cascade,
 user_id bigint not null references league_private.members(id), topic_id bigint not null,
 primary key(round_id,user_id),
 foreign key(round_id,topic_id) references league_private.topics(round_id,id)
);
create table league_private.participants (
 round_id bigint not null references league_private.rounds(id) on delete cascade,
 user_id bigint not null references league_private.members(id), status text not null check(status in ('in','out')),
 primary key(round_id,user_id)
);
create table league_private.entries (
 id bigint generated by default as identity primary key,
 round_id bigint not null references league_private.rounds(id) on delete cascade,
 user_id bigint not null references league_private.members(id),
 title text not null check(char_length(title) between 1 and 160),
 unique(round_id,user_id), unique(round_id,id),
 foreign key(round_id,user_id) references league_private.participants(round_id,user_id)
);
create table league_private.winners (
 round_id bigint not null references league_private.rounds(id) on delete cascade,
 category text not null check(char_length(category) between 1 and 160), entry_id bigint not null,
 primary key(round_id,category),
 foreign key(round_id,entry_id) references league_private.entries(round_id,id)
);
create table league_private.print_links (
 id bigint generated by default as identity primary key,
 round_id bigint not null references league_private.rounds(id) on delete cascade,
 user_id bigint not null references league_private.members(id),
 title text not null check(char_length(title) between 1 and 120),
 url text not null check(char_length(url) <= 2048 and url ~ '^https?://'),
 preview_image text not null default '' check(char_length(preview_image) <= 2048),
 unique(round_id,user_id,url),
 foreign key(round_id,user_id) references league_private.participants(round_id,user_id)
);
create table league_private.feature_ideas (
 id bigint generated by default as identity primary key,
 user_id bigint references league_private.members(id),
 title text not null check(char_length(title) between 1 and 120), normalized text not null unique,
 description text not null default '' check(char_length(description)<=1000),
 stage text not null default 'ideas' check(stage in ('ideas','progress','review')),
 created_at timestamptz not null default now()
);
-- Defense in depth: no browser policies. Future access is through narrowly scoped,
-- service-only transactional RPCs, never through browser-supplied actor IDs.
do $$ declare t record; begin
 for t in select tablename from pg_tables where schemaname='league_private' loop
  execute format('alter table league_private.%I enable row level security',t.tablename);
 end loop;
end $$;
revoke all on all tables in schema league_private from public,anon,authenticated;
revoke all on all sequences in schema league_private from public,anon,authenticated;
commit;
